import type { Context } from 'hono';
import type { ContentfulStatusCode } from 'hono/utils/http-status';
import type { z } from 'zod';

/** An error that maps directly to an HTTP response. */
export class HttpError extends Error {
  constructor(
    readonly status: ContentfulStatusCode,
    readonly code: string,
    message: string,
  ) {
    super(message);
  }
}

export const notFound = (what: string) => new HttpError(404, 'not_found', `${what} not found`);

/** Parses and validates a JSON body, turning any problem into a 400. */
export async function readJson<S extends z.ZodType>(c: Context, schema: S): Promise<z.infer<S>> {
  let raw: unknown;
  try {
    raw = await c.req.json();
  } catch {
    throw new HttpError(400, 'invalid_json', 'Request body must be valid JSON');
  }
  const parsed = schema.safeParse(raw);
  if (!parsed.success) {
    const first = parsed.error.issues[0];
    const where = first?.path.length ? first.path.join('.') : 'body';
    throw new HttpError(400, 'validation_error', `${where}: ${first?.message ?? 'invalid'}`);
  }
  return parsed.data;
}

/** IDs are generated by {@link newId}; anything else is rejected before touching storage. */
export const ID_PATTERN = /^[A-Za-z0-9_-]{8,40}$/;

export function assertId(id: string | undefined, what = 'Resource'): string {
  if (!id || !ID_PATTERN.test(id)) throw notFound(what);
  return id;
}

/** Radio Browser station ids (UUID-shaped; not all are strict RFC 4122). */
export const RB_UUID_PATTERN =
  /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;
